// Writes js/timing.js: window.WORDS (word times of the voice-over, DISPLAY words) and
// window.WAVE (loudness envelope, 100 values per second, for waveform shots).
//   node tools/timing.mjs              from audio/vo/words.json (+ audio/vo/vo.wav for WAVE)
//   node tools/timing.mjs --estimate   synthetic times from script.json, before any voice exists
// script.json: { lang, lead, tail, pauses: [...], phrases: [{ display, tts, align }] }
// A "word" = a whitespace token with a letter or digit; lone dashes are not words.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const script = JSON.parse(readFileSync(path.join(root, 'script.json'), 'utf8'));
const words = p => p.split(/\s+/).filter(w => /[\p{L}\p{N}]/u.test(w));
const want = script.phrases.flatMap(p => words(p.display));
const src = path.join(root, 'audio/vo/words.json'), wav = path.join(root, 'audio/vo/vo.wav');
let data;
if (!process.argv.includes('--estimate') && !process.argv.includes('--plan') && existsSync(src)) {
  data = JSON.parse(readFileSync(src, 'utf8'));
  if (data.words.length !== want.length) throw new Error(`words.json has ${data.words.length} words, script.json ${want.length}: regenerate the alignment`);
  data.source = 'audio/vo/words.json';
} else if (process.argv.includes('--plan')) {
  // --plan (ролик №6): фразы ровно в окнах таблицы §5 сценария v4; внутри фразы слова по слогам (align/tts-форма:
  // «чатджипити» — 4 слога, «девяносто-восемь» — 6), паузы на знаках препинания
  const WIN = [[0.1, 5.3], [5.6, 12.8], [13.1, 23.1], [23.5, 30.7], [31.0, 37.6], [38.1, 43.7], [44.9, 49.3], [49.7, 53.7], [54.0, 58.0]];
  const syl = w => Math.max(1, (w.toLowerCase().match(/[аеёиоуыэюяaeiouy]/g) || []).length);
  const ws = [], phrases = [];
  script.phrases.forEach((p, i) => {
    const [a, b] = WIN[i], dw = words(p.display), aw = words(p.align || p.display);
    const units = dw.map((w, k) => {
      const say = 0.1 + 0.075 * syl(aw[k] || w);
      const gap = /[.?!»]$/.test(w) ? 0.22 : /[,:;]$/.test(w) ? 0.11 : 0;
      const dash = p.display.includes(w + ' —') ? 0.12 : 0;
      return { w, say, gap: k === dw.length - 1 ? 0 : gap + dash };
    });
    const tot = units.reduce((s, u) => s + u.say + u.gap, 0), kq = (b - a) / tot;
    let t = a;
    units.forEach(u => { ws.push({ w: u.w, start: +t.toFixed(3), end: +(t + u.say * kq * 0.94).toFixed(3) }); t += (u.say + u.gap) * kq; });
    phrases.push({ i: i + 1, start: a, end: b, text: p.display });
  });
  data = { duration: WIN[WIN.length - 1][1] + (script.tail ?? 0.15), phrases, words: ws, source: 'estimate (plan: окна §5 сценария, слова по слогам)' };
} else {
  // --plan: the plan's grid (0.4 s per word = 2.5 w/s; «PHP» +0.4 s, «Обновление» +0.5 s — сценарий №5 §5)
  const plan = process.argv.includes('--plan'), LONG = { php: 0.4, 'обновление': 0.5 };
  // ~2.9 words/s (ru) / 2.7 (en); longer words take longer; script pauses between phrases
  const per = script.lang === 'en' ? 0.2 : 0.17, perChar = script.lang === 'en' ? 0.045 : 0.052;
  let t = script.lead ?? 0.3;
  const ws = [], phrases = [];
  script.phrases.forEach((p, i) => {
    const start = t;
    for (const w of words(p.display)) {
      const bare = w.replace(/[^\p{L}\p{N}]/gu, '');
      const d = plan ? 0.4 + (LONG[bare.toLowerCase()] || 0) : per + perChar * bare.length;
      ws.push({ w, start: t, end: t + d * 0.92 }); t += d;
    }
    phrases.push({ i: i + 1, start, end: t, text: p.display });
    if (i < script.phrases.length - 1) t += (script.pauses || [])[i] ?? 0.3;
  });
  data = { duration: t + (script.tail ?? 0.6), phrases, words: ws, source: plan ? 'estimate (plan grid 2.5 w/s)' : 'estimate' };
}
let wave = [];
if (!data.source.startsWith('estimate') && existsSync(wav)) {
  const raw = execFileSync('ffmpeg', ['-loglevel', 'error', '-i', wav, '-ac', '1', '-ar', '16000', '-f', 's16le', '-'], { maxBuffer: 1 << 28 });
  const n = raw.length / 2, hop = 160;
  for (let i = 0; i + hop <= n; i += hop) { let s = 0; for (let j = 0; j < hop; j++) { const v = raw.readInt16LE((i + j) * 2) / 32768; s += v * v; } wave.push(Math.sqrt(s / hop)); }
  const mx = Math.max(...wave) || 1;
  wave = wave.map(v => +(v / mx).toFixed(3));
} else {
  for (let i = 0; i < data.duration * 100; i++) {
    const t = i / 100, w = data.words.find(w => t >= w.start && t <= w.end);
    wave.push(w ? +(0.35 + 0.6 * Math.abs(Math.sin(t * 23)) * Math.sin(Math.PI * (t - w.start) / (w.end - w.start))).toFixed(3) : 0.02);
  }
}
writeFileSync(path.join(root, 'js/timing.js'), `// generated by tools/timing.mjs from ${data.source}\nwindow.WORDS = ${JSON.stringify(data)};\nwindow.WAVE = ${JSON.stringify(wave)};\n`);
console.log(`${data.source}: ${data.words.length} words, ${data.duration.toFixed(2)} s`);
