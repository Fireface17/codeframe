// Shiki, offline, in Node: every file in snippets/ -> tokens for the code chips (js/code.js).
// The browser never loads Shiki; it loads js/code-data.js written here.
//   node tools/tokens.mjs [--theme github-dark-high-contrast] [--lang javascript]
// Themes that read well on a phone (contrast >= 4.5:1): github-dark-high-contrast, houston.
import { createHighlighter } from 'shiki';
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (k, d) => { const i = process.argv.indexOf('--' + k); return i > 0 ? process.argv[i + 1] : d; };
const THEME = arg('theme', 'github-dark-high-contrast'), LANG = arg('lang', 'javascript');
const dir = path.join(root, 'snippets');
const names = existsSync(dir) ? readdirSync(dir).filter(f => !f.startsWith('.')).sort() : [];
// split one Shiki colour run into lexical atoms (identifier / number / string / operator / bracket / comment word);
// whitespace is dropped (position = column), comments are split into words
const LEX = /'(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*"|`(?:[^`\\\n]|\\.)*`|[\p{L}_$][\p{L}\p{N}_$]*|\d[\d_]*(?:\.\d+)?(?:e[+-]?\d+)?|\.\.\.|=>|[=!]==?|[<>]=|&&|\|\||\?\?|\+\+|--|[-+*/%&|^]=|\S/uy;
function kindMap(tok) {
  const kinds = [];
  for (const part of tok.explanation || []) {
    const sc = part.scopes.map(s => s.scopeName);
    const k = sc.some(n => n.startsWith('comment')) ? 'c' : sc.some(n => n.startsWith('string')) ? 's' : 'x';
    for (let j = 0; j < part.content.length; j++) kinds.push(k);
  }
  return i => kinds[i] || 'x';
}
function atomsOf(tok, lineStart) {
  const out = [], s = tok.content, base = tok.offset - lineStart, kindAt = kindMap(tok);
  let i = 0;
  while (i < s.length) {
    if (/\s/.test(s[i])) { i++; continue; }
    const k = kindAt(i);
    let m;
    if (k === 'c') { const w = /\S+/uy; w.lastIndex = i; m = w.exec(s)[0]; } else { LEX.lastIndex = i; m = LEX.exec(s)[0]; }
    out.push({ t: m, c: tok.color, f: tok.fontStyle || 0, col: base + i, ...(k === 'c' ? { k: 'c' } : k === 's' ? { k: 's' } : {}) });
    i += m.length;
  }
  return out;
}
const hl = await createHighlighter({ themes: [THEME], langs: [LANG] });
const all = {};
for (const f of names) {
  const code = readFileSync(path.join(dir, f), 'utf8').replace(/\n$/, '');
  const r = hl.codeToTokens(code, { lang: LANG, theme: THEME, includeExplanation: true });
  const lines = code.split('\n'), starts = [];
  let o = 0; for (const l of lines) { starts.push(o); o += l.length + 1; }
  all[f.replace(/\.[^.]+$/, '')] = { bg: r.bg, fg: r.fg, code, lines, atoms: r.tokens.map((line, li) => line.flatMap(t => atomsOf(t, starts[li]))) };
}
writeFileSync(path.join(root, 'js/code-data.js'), `// generated by tools/tokens.mjs (Shiki ${THEME}, offline)\nwindow.CODE_DATA = ${JSON.stringify(all)};\n`);
console.log(`code chips: ${Object.keys(all).map(k => `${k} ${all[k].lines.length}l/${Math.max(...all[k].lines.map(l => l.length))}c`).join(', ') || 'none (snippets/ is empty)'}`);
