// Приметы «ИИ-текста» и наших речевых привычек в сценарии ролика (русский; английские хвосты тоже).
//   node text.mjs <script.json | сценарий.md | файл.txt> [--json]
//   node text.mjs --text "Это не просто модель — это прорыв."
// script.json code-motion: берётся phrases[].display. Из .md берутся строки голоса: колонка «голос» таблицы
// или всё, кроме заголовков и служебных строк (точность ниже — лучше давать script.json).
// Это зацепки, а не вердикт. Порог для ролика ~100–150 слов: 2+ находки с низким риском ложного срабатывания — переписать.
import { readFileSync } from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2), asJson = args.includes('--json');
let phrases = [], src = '';
if (args[0] === '--text') { phrases = args.slice(1).filter(a => a !== '--json').join(' ').split(/(?<=[.!?…])\s+/); src = 'текст'; }
else if (args[0]) {
  src = args[0];
  const raw = readFileSync(src, 'utf8');
  if (src.endsWith('.json')) phrases = (JSON.parse(raw).phrases || []).map(p => p.display || p.text || '').filter(Boolean);
  else {
    const rows = raw.split('\n').filter(l => /^\|/.test(l) && !/^\|[\s|:-]+\|?$/.test(l));
    const head = rows[0] ? rows[0].split('|').map(s => s.trim().toLowerCase()) : [];
    const vi = head.findIndex(h => /голос|текст|voice|озвучк/.test(h));
    if (vi > 0) phrases = rows.slice(1).map(r => (r.split('|')[vi] || '').trim()).filter(Boolean);
    else phrases = raw.split('\n').filter(l => l.trim() && !/^(#|>|\||-{3}|```|\s*[-*]\s+\*\*|\s*\[)/.test(l)).map(l => l.replace(/[*_`]/g, '').trim());
  }
} else { console.log('Использование: node text.mjs <script.json|файл.md|файл.txt> | --text "…" [--json]'); process.exit(1); }
const text = phrases.join(' ').replace(/\s+/g, ' ');
const words = (text.match(/\p{L}[\p{L}\d-]*/gu) || []).length;

// риск ложного срабатывания: н — низкий (почти всегда шаблон), с — средний, в — высокий (считать плотность)
const W = s => new RegExp(`(?<!\\p{L})(?:${s})(?!\\p{L})`, 'giu');
const RULES = [
  // A. Зачины и связки
  ['зачин', 'н', W('давайте\\s+(разбер[её]мся|рассмотрим|посмотрим|погрузимся|начн[её]м)|погруз(имся|иться)')],
  ['зачин', 'н', W('стоит\\s+(отметить|подчеркнуть|упомянуть)|нельзя\\s+не\\s+(отметить|сказать)|важно\\s+(понимать|помнить|отметить|учитывать)')],
  ['зачин', 'н', W('в\\s+(современном|сегодняшнем|нашем)\\s+мире|в\\s+эпоху\\s+\\p{L}+|в\\s+наше\\s+время|(динамично|стремительно)\\s+(развивающ|меняющ)\\p{L}*')],
  ['зачин', 'н', W('не\\s+секрет,?\\s+что|можно\\s+с\\s+уверенностью\\s+(сказать|утверждать)|в\\s+заключени[еи]|подводя\\s+(итог|черту)|по\\s+своей\\s+сути|в\\s+конечном\\s+(сч[её]те|итоге)')],
  ['связка', 'с', W('таким\\s+образом|более\\s+того|кроме\\s+того|тем\\s+не\\s+менее|что\\s+касается')],
  ['эксперты', 'с', W('по\\s+мнению\\s+(экспертов|специалистов|уч[её]ных)|эксперты\\s+(считают|утверждают)|исследования\\s+показывают')],
  ['зачин', 'н', W('хочешь\\s+честно|и\\s+вот\\s+(здесь|тут)\\s+начинается\\s+самое\\s+интересное|отличный\\s+вопрос')],
  // B. Пустые оценки
  ['пустая оценка', 'н', W('игра(ет|ют|л[аио]?)\\s+(ключевую|важную|решающую|огромную|значительную)\\s+роль|открыва(ет|ют)\\s+(новые\\s+)?(возможности|горизонты|перспективы|двери)')],
  ['пустая оценка', 'н', W('раскры(ть|вает|вают)\\s+(сво[йё]\\s+|ваш\\s+)?потенциал|невозможно\\s+переоценить|меня(ет|ют)\\s+правила\\s+игры|изменит\\s+вс[её]|комплексн\\p{L}*\\s+подход')],
  ['слоган', 'н', W('бесшовн\\p{L}*|без\\s+усилий|переосмысл\\p{L}*|вс[её]\\s+в\\s+одном|суперсил\\p{L}*|встречайте|знакомьтесь|будущее\\s+\\p{L}+\\s+уже\\s+здесь')],
  ['громкое слово', 'с', W('уникальн\\p{L}*|невероятн\\p{L}*|революционн\\p{L}*|инновационн\\p{L}*|потрясающ\\p{L}*|шокирующ\\p{L}*|поразительн\\p{L}*')],
  ['превосходная', 'с', W('сам(ый|ая|ое|ые|ого|ую|ой|ым)\\s+\\p{L}+')],
  // C. Конструкции
  ['не X, а Y', 'н', W('не\\s+(просто|только)\\s+[^.!?]{1,40}?,?\\s+(а|но\\s+и)')],
  ['это не X — это Y', 'н', W('это\\s+не\\s+(просто\\s+)?[^.!?—]{1,40}?\\s*[—–-]\\s*это')],
  ['не X. Он Y', 'н', /(?<!\p{L})не\s+[^.!?—–]{2,40}[.!]\s+(Он|Она|Оно|Они|Это)\s/gu],
  ['больше чем', 'с', W('(больше|более),?\\s+чем\\s+(просто\\s+)?\\p{L}+')],
  ['анонс с двоеточием', 'н', /(самое\s+(странное|интересное|главное|страшное|смешное)|вот\s+(подвох|главное|в\s+ч[её]м\s+дело)|но\s+главное|секрет|фишка|подвох|причина|ответ|итог)\s*(\p{L}+\s*)?[:—–]\s*/giu],
  ['вопрос-ответ', 'с', /(?<!\p{L})(зачем|почему|откуда|как|что|кто)\s?[^.!?]{0,40}\?\s+(\p{Lu})/gu],
  ['тройка однословных', 'с', /((?<!\p{L})\p{L}+[.!](\s+|$)){3,}/gu],
  // D. Хуки и финалы-клише
  ['хук-клише', 'н', W('вы\\s+не\\s+повер(ите|ишь)|ты\\s+не\\s+повер(ишь)|знаете\\s+ли\\s+вы|а\\s+вы\\s+знали|в\\s+этом\\s+(видео|ролике)\\s+(я\\s+)?(расскажу|покажу|разбер[уё]|узнаете)|сегодня\\s+(мы\\s+)?(поговорим|расскажу|разбер[её]м)')],
  ['хук-клише', 'н', W('(досмотри|смотри)\\s+до\\s+конца|подпишись,?\\s+чтобы\\s+не\\s+пропустить|это\\s+изменит\\s+(вс[её]|вашу\\s+жизнь)|смотри\\s+внимательно')],
  ['финал-дилемма', 'н', /так\s+это\s+[^?]{2,60}\s+[—–-]?\s*или\s+[^?]{2,60}\?/giu],
  ['перешли тому', 'н', W('перешли(те)?\\s+(тому|той|другу|подруге)|отправь\\s+(тому|другу)')],
  // E. Канцелярит
  ['канцелярит', 'с', W('явля(ется|ются|лся|лась|лось|лись)|осуществл\\p{L}+|в\\s+рамках|в\\s+целях|посредством|с\\s+целью|имеет\\s+место|в\\s+связи\\s+с\\s+тем|на\\s+сегодняшний\\s+день|на\\s+данный\\s+момент')],
  // F. Английские хвосты (подписи, вставки)
  ['англ. маркер', 'н', /\b(delve|tapestry|testament|pivotal|seamless(ly)?|effortless(ly)?|unlock|game-?chang\w*|revolutioniz\w*|here'?s the (thing|kicker)|let'?s dive in|in today'?s fast-paced world)\b/gi],
  ['эмодзи', 'с', /\p{Extended_Pictographic}/gu],
];

const found = [];
for (const [name, risk, re] of RULES) for (const m of text.matchAll(re)) found.push({ name, risk, s: m[0].trim().slice(0, 60) });

// --- плотность и наши речевые привычки (по фразам)
const P = phrases.length || 1;
const dash = phrases.filter(p => /\s[—–]\s/.test(p)).length;
const dashAnd = (text.match(/[—–]\s+и\s/giu) || []).length;
const butStart = phrases.map((p, i) => [i + 1, p]).filter(([, p]) => /^(Но|А\s+вот|Однако)(?!\p{L})/u.test(p.trim()));
const one = (text.match(/(?<!\p{L})(одн(а|у|ой|о|им)|один)\s+(цифр|строк|числ|фраз|точк|слов|модел|кнопк|деталь|ошибк)\p{L}*/giu) || []);
const hedges = (text.match(/(?<!\p{L})(около|почти|примерно|порядка|больше|меньше|до)\s+\d/giu) || []).length;
const colon = phrases.filter(p => /:\s*$|\p{L}:\s/u.test(p)).length;
const metrics = [];
if (dash / P > 0.3) metrics.push(`тире в ${Math.round(100 * dash / P)}% фраз (${dash} из ${P}) — половину заменить точкой: «Поменял цифру. Ролик пересобрался».`);
if (dashAnd >= 2) metrics.push(`кульминация «— и …» ×${dashAnd} — одна на ролик максимум.`);
if (butStart.length >= 2) metrics.push(`фразы с «Но/А вот/Однако» в начале: №${butStart.map(b => b[0]).join(', №')} — повороты встык новым фактом, в разных местах; один ролик вообще без «но».`);
else if (butStart.length === 1 && butStart[0][0] <= 4 && P >= 8) metrics.push(`«Но» на ${butStart[0][0]}-й фразе — наш стандартный поворот; проверь, не по привычке ли.`);
if (one.length) metrics.push(`мотив «одна X → большой эффект»: ${one.slice(0, 3).join(', ')} — точная величина вместо «одна».`);
if (hedges >= 3) metrics.push(`оговорки «около/почти/примерно» перед числами ×${hedges} — одна на число, остальное в описание.`);
if (colon >= 2) metrics.push(`фраз с двоеточием-анонсом ${colon} — сразу факт без анонса.`);

const RISKW = { н: 3, с: 1, в: 0.5 };
const score = found.reduce((s, f) => s + RISKW[f.risk], 0) + metrics.length * 2;
if (asJson) { console.log(JSON.stringify({ src, phrases: P, words, score, found, metrics }, null, 1)); process.exit(0); }

console.log(`# Текст: ${src === 'текст' ? 'из командной строки' : path.basename(src)} — ${P} фраз, ${words} слов\n`);
if (!found.length && !metrics.length) console.log('Явных примет ИИ-текста не найдено. Проверь глазами: можно ли вставить фразу в любой другой ролик?');
const by = {};
for (const f of found) (by[`${f.name} (${f.risk})`] ||= []).push(f.s);
for (const [k, list] of Object.entries(by).sort((a, b) => b[1].length - a[1].length)) console.log(`- ${k} ×${list.length}: ${[...new Set(list)].slice(0, 4).map(s => `«${s}»`).join(', ')}`);
if (metrics.length) { console.log('\nПривычки по ролику:'); for (const m of metrics) console.log(`- ${m}`); }
console.log(`\nБалл шаблонности текста: ${Math.round(score)} (0–3 чисто · 4–9 переписать отмеченное · 10+ текст звучит как ИИ)`);
console.log('Риск ложного срабатывания: н — низкий, с — средний (смотри плотность), в — высокий.');
