// Лаборатория идей: одна страница index.html, идея выбирается ?idea=<slug>.
//   node tools/lab.mjs list                          все идеи из ideas/registry.js
//   node tools/lab.mjs prep [slug|all]               тайминг (script.json -> timing.js) и плашки кода (snippets -> code-data.js)
//   node tools/lab.mjs sheet <slug> [t,t,...] [cols] контактный лист -> out/sheets/<slug>.png (по умолчанию 8 точек)
//   node tools/lab.mjs draft <slug>                  быстрый черновик SUB=4 -> out/drafts/<slug>.mp4
//   node tools/lab.mjs render <slug|all> [jobs]      превью с motion blur -> out/previews/<slug>.mp4 + _web.mp4 + .jpg
//   node tools/lab.mjs check <slug|all>              безопасная зона + шов петли + рывки (по превью или черновику)
//   node tools/lab.mjs new <slug> [WxH] "Название"   папка идеи из заготовки + meta.json
// Открыть идею в браузере: open "index.html?idea=<slug>" (пробел, стрелки, g — безопасная зона).
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sh = (cmd, args, env = {}) => execFileSync(cmd, args, { cwd: root, stdio: ['ignore', 'pipe', 'inherit'], env: { ...process.env, ...env } }).toString();
const run = (cmd, args, env = {}) => execFileSync(cmd, args, { cwd: root, stdio: 'inherit', env: { ...process.env, ...env } });

// Реестр собирается из ideas/<slug>/meta.json (каждая идея описывает себя сама, общий файл
// никто не правит руками): { title, size: [W, H], fps, kind, tags, about, src: { name, url, license }, poster? }
function registry() {
  const dir = path.join(root, 'ideas');
  const list = readdirSync(dir).filter(d => existsSync(path.join(dir, d, 'meta.json'))).sort()
    .map(d => ({ slug: d, ...JSON.parse(readFileSync(path.join(dir, d, 'meta.json'), 'utf8')) }));
  const js = `// generated by tools/lab.mjs from ideas/*/meta.json: не править руками\nwindow.IDEAS = ${JSON.stringify(list, null, 1)};\n`;
  const f = path.join(dir, 'registry.js');
  if (!existsSync(f) || readFileSync(f, 'utf8') !== js) writeFileSync(f, js);
  return list;
}
const ideas = registry();
const byslug = s => { const I = ideas.find(i => i.slug === s); if (!I) throw new Error(`нет идеи «${s}» в ideas/registry.js`); return I; };
const pick = s => (s === 'all' || !s ? ideas : [byslug(s)]);

function prep(I) {
  const dir = path.join('ideas', I.slug);
  sh('node', ['tools/timing.mjs', '--dir', dir]);
  sh('node', ['tools/tokens.mjs', '--dir', dir]);
}
function duration(I) {
  const out = sh('node', ['render.mjs', 'cues'], { QUERY: `idea=${I.slug}` });
  return JSON.parse(out).duration;
}
const fmtT = ts => ts.map(t => t.toFixed(2)).join(',');

const [cmd, a1, a2, a3] = process.argv.slice(2);
if (cmd === 'list' || !cmd) {
  for (const I of ideas) {
    const prev = path.join(root, 'out/previews', I.slug + '.mp4');
    console.log(`${I.slug.padEnd(24)} ${I.size.join('x').padEnd(10)} ${(I.kind || '').padEnd(22)} ${existsSync(prev) ? 'превью ✓' : 'нет превью'}  ${I.title}`);
  }
} else if (cmd === 'prep') {
  for (const I of pick(a1)) { prep(I); console.log('prep', I.slug); }
} else if (cmd === 'sheet') {
  const I = byslug(a1); prep(I);
  mkdirSync(path.join(root, 'out/sheets'), { recursive: true });
  let ts = a2;
  if (!ts) { const D = duration(I); ts = fmtT(Array.from({ length: 8 }, (_, k) => (k + 0.5) * D / 8)); }
  run('node', ['render.mjs', 'sheet', `out/sheets/${I.slug}.png`, ts, a3 || (I.size[0] > I.size[1] ? '2' : '4')], { QUERY: `idea=${I.slug}` });
} else if (cmd === 'draft') {
  const I = byslug(a1); prep(I);
  mkdirSync(path.join(root, 'out/drafts'), { recursive: true });
  run('node', ['render.mjs', 'video', `out/drafts/${I.slug}.mp4`, process.env.JOBS || '6'], { QUERY: `idea=${I.slug}`, SUB: '4' });
} else if (cmd === 'render') {
  mkdirSync(path.join(root, 'out/previews'), { recursive: true });
  for (const I of pick(a1)) {
    prep(I);
    const base = `out/previews/${I.slug}`;
    run('node', ['render.mjs', 'video', `${base}.mp4`, a2 || '6'], { QUERY: `idea=${I.slug}` });
    const D = duration(I), tp = I.poster ?? +(D * 0.62).toFixed(2);
    // лёгкая версия для галереи: половина размера, crf 24
    run('ffmpeg', ['-loglevel', 'error', '-y', '-i', `${base}.mp4`, '-vf', 'scale=iw/2:-2:flags=lanczos', '-c:v', 'libx264', '-crf', '24', '-preset', 'slow',
      '-pix_fmt', 'yuv420p', '-movflags', '+faststart', '-an', `${base}_web.mp4`]);
    run('ffmpeg', ['-loglevel', 'error', '-y', '-ss', String(tp), '-i', `${base}.mp4`, '-frames:v', '1', '-vf', 'scale=iw/2:-2', '-q:v', '3', `${base}.jpg`]);
    const mb = f => (statSync(path.join(root, f)).size / 1e6).toFixed(1);
    console.log(`✓ ${I.slug}: ${D.toFixed(2)} с · ${mb(base + '.mp4')} МБ (web ${mb(base + '_web.mp4')} МБ)`);
  }
} else if (cmd === 'check') {
  // безопасная зона (по странице), шов петли и рывки (по превью, иначе по черновику)
  for (const I of pick(a1)) {
    prep(I);
    console.log(`--- ${I.slug}`);
    try { run('node', ['tools/safecheck.mjs', '0.05'], { QUERY: `idea=${I.slug}` }); } catch { process.exitCode = 1; }
    const v = [`out/previews/${I.slug}.mp4`, `out/drafts/${I.slug}.mp4`].find(f => existsSync(path.join(root, f)));
    if (!v) { console.log('  нет видео для loopcheck/jumps: сначала draft или render'); continue; }
    console.log(`  видео: ${v}`);
    run('uv', ['run', '--script', 'tools/loopcheck.py', v]);
    run('uv', ['run', '--script', 'tools/jumps.py', v]);
  }
} else if (cmd === 'new') {
  const slug = a1, [w, h] = (a2 || '1080x1920').split('x').map(Number), title = a3 || slug;
  if (!slug || existsSync(path.join(root, 'ideas', slug))) throw new Error('нужен новый slug');
  const dir = path.join(root, 'ideas', slug);
  mkdirSync(dir, { recursive: true });
  writeFileSync(path.join(dir, 'film.js'), readFileSync(path.join(root, 'tools/idea-skeleton.js'), 'utf8'));
  writeFileSync(path.join(dir, 'meta.json'), JSON.stringify({ title, size: [w, h], fps: 60, kind: '', tags: [], about: '', src: { name: 'своя', url: '', license: '' } }, null, 1) + '\n');
  registry();
  console.log(`ideas/${slug}/ создана (film.js, meta.json), реестр обновлён. Открыть: open "index.html?idea=${slug}"`);
} else {
  console.log(readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').filter(l => l.startsWith('//')).join('\n'));
}
